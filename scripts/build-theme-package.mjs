// Builds release/baaboul-houda-theme.zip: ONE self-contained, installable
// WordPress theme (Apparence > Thèmes > Ajouter > Téléverser).
//
// The theme normally depends on the "Baaboul Houda Core" plugin (post types,
// settings, prayer times, Quran, forms...). This script bundles that plugin
// into the theme under core/ and loads it from functions.php, so no separate
// plugin install is needed. Sources are never modified: patches are applied
// to a staging copy only.
//
// Usage: npm run build (assets), then  npm run release:theme
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const themeSrc = join(root, 'site/wp-content/themes/baaboul-houda');
const pluginSrc = join(root, 'site/wp-content/plugins/baaboul-houda-core');
const outDir = join(root, 'release');
const stageRoot = join(outDir, '_theme-stage');
const stage = join(stageRoot, 'baaboul-houda');
const zip = join(outDir, 'baaboul-houda-theme.zip');

const skip = (p) => /[\\/](node_modules|assets-src|\.git)([\\/]|$)/.test(p);

function patch(file, fn) {
  const before = readFileSync(file, 'utf8');
  const after = fn(before);
  if (after === before) throw new Error(`patch had no effect: ${file}`);
  writeFileSync(file, after);
}

if (!existsSync(join(themeSrc, 'assets/dist/js/main.js'))) {
  throw new Error('Theme assets are not built. Run `npm run build` first.');
}

rmSync(stageRoot, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });

// 1. Theme (pre-built assets included, sources excluded).
cpSync(themeSrc, stage, { recursive: true, filter: (s) => !skip(s) });

// 2. Core plugin -> core/ (code, data, admin assets).
const core = join(stage, 'core');
for (const dir of ['includes', 'data', 'assets/dist']) {
  cpSync(join(pluginSrc, dir), join(core, dir), { recursive: true, filter: (s) => !skip(s) });
}

// 3. Bootstrap = the plugin's main file, minus the plugin header, re-pointed at the theme.
const main = readFileSync(join(pluginSrc, 'baaboul-houda-core.php'), 'utf8');
const body = main
  .replace(/^<\?php\s*\/\*\*[\s\S]*?\*\/\s*/, '')
  .replace('plugin_dir_path(__FILE__)', "trailingslashit(__DIR__)")
  .replace('plugin_dir_url(__FILE__)', "trailingslashit(get_template_directory_uri() . '/core')");
writeFileSync(
  join(core, 'bootstrap.php'),
  `<?php\n/**\n * Bundled core (formerly the "Baaboul Houda Core" plugin). Generated by\n * scripts/build-theme-package.mjs. Skipped if the standalone plugin is active.\n */\n\ndefined('ABSPATH') || exit;\n\nif (defined('BH_VERSION')) {\n    return;\n}\n\n${body}`,
);

// 4. Activation: a theme has no activation hook -> use after_switch_theme.
patch(join(core, 'includes/activation.php'), (s) =>
  s
    .replace("register_activation_hook(BH_CORE_FILE, 'bh_activate');", "add_action('after_switch_theme', 'bh_activate');")
    .replace("register_deactivation_hook(BH_CORE_FILE, 'bh_deactivate');", "add_action('switch_theme', 'bh_deactivate');"),
);

// 5. Load the bundled core before anything in the theme calls bh_*().
patch(join(stage, 'functions.php'), (s) =>
  s.replace(/defined\('ABSPATH'\) \|\| exit;\r?\n/, (m) => `${m}\nrequire_once get_template_directory() . '/core/bootstrap.php';\n`),
);

// 6. Theme header: extra metadata for the WP themes screen.
patch(join(stage, 'style.css'), (s) =>
  s.replace(/Version: 1\.0\.0\r?\n/, (m) => `${m}Requires at least: 6.0\nRequires PHP: 8.1\nLicense: GPL-2.0-or-later\nLicense URI: https://www.gnu.org/licenses/gpl-2.0.html\n`),
);

// 7. Zip (folder name at the archive root = theme slug).
rmSync(zip, { force: true });
execFileSync('tar', ['-a', '-cf', zip, '-C', stageRoot, 'baaboul-houda'], { stdio: 'inherit' });
rmSync(stageRoot, { recursive: true, force: true });

console.log(`OK ${zip} (${(statSync(zip).size / 1048576).toFixed(1)} MB)`);
